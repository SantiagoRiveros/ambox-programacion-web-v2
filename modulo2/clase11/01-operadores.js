/* 
OPERADORES ARITMETICOS:
+ Suma
- Resta
* Multiplicacion
/ Division
% Resto (Modulo)
** Potencia
*/

let numero1 = 10;
let numero2 = 3;

console.log("Suma:");
console.log(numero1 + numero2);
console.log("Resta:");
console.log(numero1 - numero2);
console.log("Multiplicacion:");
console.log(numero1 * numero2);
console.log("Division:");
console.log(numero1 / numero2);
console.log("Modulo:");
console.log(numero1 % numero2);
console.log("Potencia:");
console.log(numero1 ** numero2);

/* 
Operadores de Comparacion:
Estos no hacen calculos sino que comparan valores

el resultado siempre es:
true o false
*/

console.log("-------------------------");
console.log("OPERADORES DE COMPARACION");

console.log("Mayor que:");
console.log(3 > 2);
console.log(3 > 9);

console.log("Menor que:");
console.log(8 < 9);
console.log(8 < 7);

console.log("Mayor igual que:");
console.log(8 >= 8);
console.log(8 >= 9);

console.log("Menor igual que:");
console.log(20 <= 30);
console.log(20 <= 10);

console.log("Igualdad");
console.log(3 == "3"); // Esto es verdadero
console.log(3 == "a");

console.log("igualdad estricta");
console.log(3 === 3);
console.log(3 === "3"); // falso

console.log("desigualdad");
console.log(3 !== 4);
console.log(3 !== 3);

